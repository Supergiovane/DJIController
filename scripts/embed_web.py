"""PlatformIO pre-build step: gzips web/index.html into src/generated/WebAssets.h.

The header is rewritten only when its content changes, so unchanged UI doesn't trigger a rebuild.
"""

import gzip
from pathlib import Path

Import("env")  # noqa: F821 - injected by PlatformIO/SCons

project = Path(env["PROJECT_DIR"])  # noqa: F821
source = project / "web" / "index.html"
target = project / "src" / "generated" / "WebAssets.h"

data = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
header = (
    "#pragma once\n\n"
    "#include <Arduino.h>\n\n"
    "// Generated by scripts/embed_web.py from web/index.html. Do not edit.\n"
    "static const uint8_t kIndexHtmlGz[] PROGMEM = {\n  " + ",\n  ".join(rows) + "\n};\n"
    f"static const size_t kIndexHtmlGzLen = {len(data)};\n"
)

target.parent.mkdir(parents=True, exist_ok=True)
if not target.exists() or target.read_text() != header:
    target.write_text(header)
    print(f"embed_web: {source.name} -> {target.relative_to(project)} ({len(data)} bytes gzipped)")
